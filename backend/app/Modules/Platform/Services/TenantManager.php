<?php

namespace App\Modules\Platform\Services;

use App\Models\User;
use App\Modules\Platform\Models\Council;
use App\Modules\Platform\Models\Membership;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Facades\DB;

/**
 * Holds the validated council and membership for the current request and
 * owns the lifecycle of the `tenant` database connection.
 */
class TenantManager
{
    private ?Council $council = null;

    private ?Membership $membership = null;

    public function council(): ?Council
    {
        return $this->council;
    }

    public function requireCouncil(): Council
    {
        if (! $this->council instanceof Council) {
            abort(409, 'No council context has been resolved for this request.');
        }

        return $this->council;
    }

    public function membership(): ?Membership
    {
        return $this->membership;
    }

    public function requireMembership(): Membership
    {
        if (! $this->membership instanceof Membership) {
            abort(403, 'You do not have an active membership in this council.');
        }

        return $this->membership;
    }

    public function connect(Council $council, ?Membership $membership = null, bool $allowInactive = false): void
    {
        if (! $allowInactive && ! $council->isActive()) {
            abort(403, 'This council is not active.');
        }

        $this->guardDatabaseName($council->database_name);

        $alreadyConnected = false;

        try {
            $alreadyConnected = DB::connection('tenant')->getDatabaseName() === $council->database_name;
        } catch (\Throwable) {
            $alreadyConnected = false;
        }

        if (! $alreadyConnected) {
            config([
                'database.connections.tenant.database' => $council->database_name,
            ]);

            DB::purge('tenant');
            DB::reconnect('tenant');
        }

        $this->council = $council;
        $this->membership = $membership;
    }

    /**
     * Bind the request context when the tenant connection already points at
     * the council database (used by the console/test harness).
     */
    public function useContext(Council $council, ?Membership $membership = null): void
    {
        if (DB::connection('tenant')->getDatabaseName() !== $council->database_name) {
            throw new \RuntimeException('Tenant connection is not pointed at this council database.');
        }

        $this->council = $council;
        $this->membership = $membership;
    }

    /**
     * Run a callback in a validated council context. Always restores the
     * previous context, so queued jobs cannot leak tenant state.
     */
    public function runFor(Council $council, callable $callback): mixed
    {
        $previousCouncil = $this->council;
        $previousMembership = $this->membership;

        try {
            $this->connect($council);

            return $callback($council);
        } finally {
            if ($previousCouncil instanceof Council) {
                $this->connect($previousCouncil, $previousMembership);
            } else {
                $this->clear();
            }
        }
    }

    public function clear(): void
    {
        $this->council = null;
        $this->membership = null;
        DB::purge('tenant');
    }

    public function assertConnectedTo(Council $council): void
    {
        $actual = DB::connection('tenant')->getDatabaseName();

        if ($actual !== $council->database_name) {
            throw new \RuntimeException("Tenant connection points at [{$actual}], expected [{$council->database_name}].");
        }
    }

    public function currentUser(): ?User
    {
        return Auth::user();
    }

    /**
     * Database identifiers are generated by the provisioner only. Reject
     * anything that is not a simple, prefixed identifier.
     */
    private function guardDatabaseName(string $name): void
    {
        if (! preg_match('/^[a-z][a-z0-9_]{2,62}$/', $name)) {
            throw new \RuntimeException('Unsafe tenant database identifier.');
        }
    }
}
